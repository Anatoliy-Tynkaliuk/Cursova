import { API_URL } from "./config";
import { getToken } from "./auth";

type Method = "GET" | "POST" | "PATCH" | "DELETE";

// Функція: api. Виконує локальну частину логіки файлу та взаємодіє з залежностями через параметри/імпорти.
// Функція: api. Крок за кроком приймає вхідні дані, перевіряє їх та повертає прогнозований результат.
export async function api<T>(path: string, method: Method = "GET", body?: any): Promise<T> {
  const headers: Record<string, string> = { "Content-Type": "application/json" };

  const token = getToken();
  if (token) headers.Authorization = `Bearer ${token}`;

  const res = await fetch(`${API_URL}${path}`, {
    method,
    headers,
    body: body ? JSON.stringify(body) : undefined,
    cache: "no-store",
  });

  if (!res.ok) {
    let msg = "API error";
    try {
      const data = await res.json();
      msg = data?.message || msg;
    } catch {}
    throw new Error(msg);
  }

  return res.json();
}
