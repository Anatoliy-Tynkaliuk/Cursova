import 'dotenv/config';
import { NestFactory } from '@nestjs/core';
import { AppModule } from './app.module';

// Функція: bootstrap. Виконує локальну частину логіки файлу та взаємодіє з залежностями через параметри/імпорти.
// Функція: bootstrap. Крок за кроком приймає вхідні дані, перевіряє їх та повертає прогнозований результат.
async function bootstrap() {
  const app = await NestFactory.create(AppModule);

  app.enableCors({
    origin: 'http://localhost:3000',
    credentials: true,
  });

  await app.listen(process.env.PORT ?? 3001);
}
bootstrap();
